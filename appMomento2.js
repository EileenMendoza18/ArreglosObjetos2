//momento 2
// a. Creamos el arreglo con 4 verduras
let verduras = ["Zanahoria", "Cebolla", "Tomate", "Brócoli"];
console.log("Arreglo inicial:", verduras);

// b. Operaciones de manipulación

// push(): Agrega un elemento al final
verduras.push("Espárrago");
console.log("Después de push():", verduras);

// pop(): Elimina el último elemento
verduras.pop();
console.log("Después de pop():", verduras);

// unshift(): Agrega un elemento al inicio
verduras.unshift("Espinaca");
console.log("Después de unshift():", verduras);

// shift(): Elimina el primer elemento
verduras.shift();
console.log("Después de shift():", verduras);