// 1. Arreglo inicial
let frutas = ["Manzana", "Pera", "Banano"];
console.log("Inicio:", frutas);

// 2. Agregue "Mango" al final
frutas.push("Mango");
console.log("Después de push:", frutas);

// 3. Elimine el último elemento
frutas.pop();
console.log("Después de pop:", frutas);

// 4. Agregue "Uva" al inicio
frutas.unshift("Uva");
console.log("Después de unshift:", frutas);

// 5. Elimine el primer elemento
frutas.shift();
console.log("Después de shift:", frutas);

// 6. Escriba cuántos elementos tiene el arreglo actualmente
let cantidad = frutas.length;

console.log("Resultado final:", frutas);
console.log("Número de elementos:", cantidad);

